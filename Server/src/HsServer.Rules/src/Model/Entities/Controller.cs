		/// <summary>
		/// Adds a new Hero entity and HeroPower entity to the game instance.
		/// </summary>
		/// <param name="heroCard">The card to derive the hero entity from.</param>
		/// <param name="powerCard">The heropower card to derive the hero power entity from.</param>
		/// <param name="tags">The inherited tags</param>
		/// <param name="id">The entity id to assign to the generated HERO entity</param>
		public void AddHeroAndPower(in Card heroCard, in Card powerCard = null, in IDictionary<GameTag, int> tags = null, in int id = -1)
		{
			// remove hero and place it to the setaside zone
			Weapon weapon = null;
			AuraEffects auraEffects = null;
			if  (Hero != null)
			{
				SetasideZone.MoveTo(Hero, SetasideZone.Count);
				SetasideZone.MoveTo(Hero.HeroPower, SetasideZone.Count);
				Actions.Generic.RetireFromPlay(Hero);
				Actions.Generic.RetireFromPlay(Hero.HeroPower);
				//Hero[GameTag.EXHAUSTED] = 0;
				//Hero[GameTag.NUM_ATTACKS_THIS_TURN ] = 0;
				//Hero[GameTag.DAMAGE] = 0;
				//Hero[GameTag.REVEALED] = 1;
				if (Hero.Weapon != null)
				{
					weapon = Hero.Weapon;
				}

				auraEffects = Hero.AuraEffects;
			}


			// HsServer: the hero is created in PLAY (live FULL_ENTITY has ZONE=PLAY). Created zoneless, the opponent's hero
			// came out hidden and was then revealed, which crashed the client (Entity.GetClass on an unknown entity).
			var heroTags = tags != null ? new EntityData(tags) : new EntityData();
			heroTags[GameTag.ZONE] = (int) Enums.Zone.PLAY;
			// HsServer: the hero power as the current client knows it (basic hero powers were renamed, e.g.
			// CS2_083b → HERO_03bp; the client can't load the old ids), and the hero's HERO_POWER tag pointing at it.
			Card asked = powerCard ?? Cards.FromAssetId(heroCard[GameTag.HERO_POWER]);
			// HsServer (2026-10-09): a hero with no Hero Power (Bartender Bob: no HERO_POWER in its card data, none in live's CREATE_GAME)
			// gets a set-aside stand-in the client doesn't show — the engine always has one (its class's basic one)
			Card standIn = !(heroCard.Class is >= CardClass.DEATHKNIGHT and <= CardClass.WARRIOR or CardClass.DEMONHUNTER) ? null
				: Cards.FromAssetId(Cards.HeroCard(heroCard.Class)?[GameTag.HERO_POWER] ?? 0);
			Card power = Loader.ReprintCards.Current(asked ?? standIn ?? Cards.FromId("HERO_08bp"));
			if (asked != null) heroTags[GameTag.HERO_POWER] = power.AssetId;
			Hero = (Hero) FromCard(this, in heroCard, heroTags, null, id);
			Hero[GameTag.ZONE] = (int) Enums.Zone.PLAY;
			HeroId = Hero.Id;
			Hero.HeroPower = FromCard(this, power, new EntityData { [GameTag.CREATOR] = Hero.Id }, asked == null ? SetasideZone : null) as HeroPower;
			Hero.Weapon = weapon;
			Hero.AuraEffects = auraEffects;
		}

		/// <summary>
		/// Build a unique string describing this object.
		/// </summary>
		/// <param name="ignore">All GameTags which have to be ignored during hash generation.</param>
		/// <returns>The unique hash string.</returns>
		public override string Hash(params GameTag[] ignore)
		{
			var str = new StringBuilder();
			str.Append("[C:");
			str.Append(Name);
			str.Append("]");
			str.Append(base.Hash(ignore));
			str.Append(ControllerAuraEffects.Hash());
			str.Append(Hero.Hash(ignore));
			str.Append(Hero.HeroPower.Hash(ignore));
			if (Hero.Weapon != null)
				str.Append(Hero.Weapon.Hash(ignore));
			str.Append(ControlledZones.Hash(ignore));
			return str.ToString();
		}

		/// <summary>
		/// Returns a set of all options this player can perform execute at the moment.
		/// From this set one option is picked and executed by the game.
		/// </summary>
		/// <param name="skipPrePhase">Doesn't check validity of the options generated from this when it is processed.</param>
		/// <returns></returns>
		public List<PlayerTask> Options(bool skipPrePhase = true)
		{
			// No options for the opponent player.
			if (this != Game.CurrentPlayer)
				return new List<PlayerTask>(0);

			//	ChooseTasks
			if (Choice != null)
			{
				switch (Choice.ChoiceType)
				{
					case ChoiceType.GENERAL:
					case ChoiceType.TARGET: // HsServer: Generic.PickTargets
						return Choice.Choices.Select(p => (PlayerTask)ChooseTask.Pick(this, p)).ToList();

					case ChoiceType.MULLIGAN:
						IEnumerable<IEnumerable<int>> choices = Util.GetPowerSet(Choice.Choices);
						return choices.Select(p => (PlayerTask) ChooseTask.Mulligan(this, p.ToList())).ToList();

					default:
						throw new NotImplementedException();
				}
			}

			// no options till mulligan is done for both players
			if (Game.Step != Step.MAIN_ACTION)
				return new List<PlayerTask>(0);

			//	EndTurnTask
			var allOptions = new List<PlayerTask>(20) { EndTurnTask.Any(this) };

			#region PlayCardTasks
			int mana = RemainingMana;
			int zonePosRange = BoardZone.Count;
			// HsServer (2026-10-08): on a full board a Magnetic minion's slots are those left of a Mech it can join (wiki Magnetic.txt:7)
			bool MinionSlotOk(IPlayable p, int slot) => !BoardZone.IsFull || Actions.Generic.MagnetizeHostAt(this, p.Card, slot) != null;
			bool? spellCostHealth = null;

			Character[] allTargets = null;
			Minion[] friendlyMinions = null;
			Minion[] enemyMinions = null;
			Minion[] allMinions = null;
			Character[] allFriendly = null;
			Character[] allEnemies = null;

			var handSpan = HandZone.GetSpan();
			for (int i = 0; i < handSpan.Length; i++)
			{
				if (Playable.IsPlayRestricted(handSpan[i])) continue; // HsServer: Prosecutor Mel'tranix
				if (!handSpan[i].ChooseOne || ChooseBothCards || handSpan[i][GameTag.CHOOSE_BOTH] > 0 || handSpan[i].ChooseOnePlayables == null) // HsServer: options unknown = plain card
					GetPlayCardTasks(handSpan[i]);
				else
				{
					IPlayable[] playables = handSpan[i].ChooseOnePlayables;
					for (int j = 1; j < 3; j++)
						GetPlayCardTasks(handSpan[i], playables[j - 1], j);
				}
			}
			#endregion

			// HsServer (VIOLET_HOLD): Free placement — a Disguised minion that can be played may also go to the opponent's board
			if (!Opponent.BoardZone.IsFull)
				foreach (PlayCardTask play in allOptions.OfType<PlayCardTask>().Where(p => !p.Disguised && p.Source is Minion && p.Source.Card[Actions.Generic.DISGUISED] > 0)
					         .GroupBy(p => (p.Source.Id, p.TargetEntity?.Id, p.ChooseOne)).Select(x => x.First()).ToList())
					allOptions.Add(new PlayCardTask(this, play.Source, play.Target, -1, play.ChooseOne) { Disguised = true });

			// HsServer: trade Tradeable cards (shuffle into the deck for their trade cost, draw a card)
			for (int i = 0; i < handSpan.Length; i++)
			{
				if (Actions.Generic.CanTrade(this, handSpan[i]))
					allOptions.Add(TradeTask.Any(this, handSpan[i]));
				if (Actions.Generic.CanForge(this, handSpan[i])) // HsServer: Forge (its own option, like a trade)
					allOptions.Add(ForgeTask.Any(this, handSpan[i]));
				if (Actions.Generic.CanPrepare(this, handSpan[i])) // HsServer (VIOLET_HOLD): Prepare (its own deck-action option)
					allOptions.Add(PrepareTask.Any(this, handSpan[i]));
			}

			#region HeroPowerTask
			HeroPower power = Hero.HeroPower;
			Card heroPowerCard = power.Card;
			if (!power.IsExhausted && mana >= power.Cost &&
			    !HeroPowerDisabled && !heroPowerCard.HideStat)
			{
				if (heroPowerCard.ChooseOne && power.ChooseOnePlayables != null) // HsServer: options unknown = plain power
				{
					if (ChooseBoth)
						allOptions.Add(HeroPowerTask.Any(this, skipPrePhase: true));
					else
					{
						allOptions.Add(HeroPowerTask.Any(this, null, 1, true));
						allOptions.Add(HeroPowerTask.Any(this, null, 2, true));
					}
				}
				else
				{
					if (heroPowerCard.IsPlayableByCardReq(this))
					{
						Character[] targets = GetTargets(heroPowerCard);
						// HsServer: Steamwheedle Sniper - a Steady Shot (REQ_STEADY_SHOT) may target any minion or the enemy hero.
						if (targets == null && SteadyShotCanTarget && heroPowerCard.PlayRequirements != null &&
						    heroPowerCard.PlayRequirements.ContainsKey(PlayReq.REQ_STEADY_SHOT))
							targets = BoardZone.GetAll().Concat(Opponent.BoardZone.GetAll()).Where(m => !m.CantBeTargetedByHeroPowers && (m.Controller == this || !m.HasStealth && !m.IsImmune))
								.Cast<Character>().Concat(Opponent.Hero.HasStealth || Opponent.Hero.IsImmune ? new Character[0] : new Character[] { Opponent.Hero })
								.ToArray();
						if (targets != null)
							for (int i = 0; i < targets.Length; i++)
								allOptions.Add(HeroPowerTask.Any(this, targets[i], skipPrePhase: true));
						else
							allOptions.Add(HeroPowerTask.Any(this, skipPrePhase: true));
					}
				}
			}
			#endregion

			// HsServer (VIOLET_HOLD): a second Hero Power (Thal'ena's Vampyr's Kiss), its own uses
			if (Actions.Generic.SecondHeroPower(this) is HeroPower second && !second.IsExhausted && second.IsPlayable && !second.Card.HideStat)
			{
				Character[] secondTargets = GetTargets(second.Card);
				if (secondTargets != null)
					foreach (Character t in secondTargets)
						allOptions.Add(HeroPowerTask.Any(this, t, skipPrePhase: false, power: second));
				else
					allOptions.Add(HeroPowerTask.Any(this, power: second));
			}

			// HsServer: activate Locations (one move per valid target, or one untargeted move)
			foreach (Minion onBoard in BoardZone.GetSpan().ToArray())
			{
				if (!(onBoard is Location location) || !location.CanActivate)
					continue;
				List<IPlayable> activationTargets = location.ActivationTargets();
				if (activationTargets == null || activationTargets.Count == 0)
					allOptions.Add(LocationTask.Any(this, location));
				else
					foreach (IPlayable target in activationTargets)
						allOptions.Add(LocationTask.Any(this, location, target));
			}

			// HsServer (TITANS): a Titan's abilities, one move per usable ability and target (Actions/Titans.cs)
			foreach (Minion onBoard in BoardZone.GetSpan().ToArray())
				if (Actions.Generic.IsTitan(onBoard))
					allOptions.AddRange(Actions.Generic.TitanAbilityTasks(this, onBoard));
			// HsServer (SPACE): the Starship's launch (Actions/Starship.cs)
			if (Actions.Generic.BuildingStarship(this) is Minion starship && Actions.Generic.CanLaunch(this, starship))
				allOptions.Add(StarshipLaunchTask.Any(this, starship));
			// HsServer (LOST_CITY): interactable objects (the Underfel Rift)
			allOptions.AddRange(Actions.Generic.InteractTasks(this));

			#region MinionAttackTasks
			Minion[] attackTargets = null;
			bool isOpHeroValidAttackTarget = false;
			var boardSpan = BoardZone.GetSpan();
			for (int j = 0; j < boardSpan.Length; j++)
			{
				Minion minion = boardSpan[j];

				if (minion.IsExhausted && (!minion.HasCharge || minion.NumAttacksThisTurn != 0))
					continue;
				if (minion.IsFrozen || minion.AttackDamage == 0 || minion.CantAttack || minion.Untouchable)
					continue;
				if (Actions.Generic.TitanHasAbilitiesLeft(minion)) // HsServer (TITANS): abilities instead of attacking
					continue;

				GenerateAttackTargets();

				// HsServer: an attacker that ignores Taunt (Kayn Sunfury) may attack any visible enemy.
				bool ignoresTaunt = minion[GameTag.IGNORE_TAUNT] > 0;
				Minion[] targetsForThis = ignoresTaunt ? GetEnemyMinions() : attackTargets;
				for (int i = 0; i < targetsForThis.Length; i++)
					allOptions.Add(MinionAttackTask.Any(this, minion, targetsForThis[i], skipPrePhase));

				if ((ignoresTaunt ? OpHeroAttackable() : isOpHeroValidAttackTarget) && !(minion.CantAttackHeroes || minion.AttackableByRush))
					allOptions.Add(MinionAttackTask.Any(this, minion, Opponent.Hero, skipPrePhase));
			}
			#endregion

			#region HeroAttackTaskts
			Hero hero = Hero;

			if ((!hero.IsExhausted || (hero.ExtraAttacksThisTurn > 0 && hero.ExtraAttacksThisTurn >= hero.NumAttacksThisTurn))
			    && hero.AttackDamage > 0 && !hero.IsFrozen)
			{
				GenerateAttackTargets();

				bool ignoresTaunt = hero[GameTag.IGNORE_TAUNT] > 0; // HsServer (Kayn Sunfury)
				Minion[] targetsForHero = ignoresTaunt ? GetEnemyMinions() : attackTargets;
				for (int i = 0; i < targetsForHero.Length; i++)
					allOptions.Add(HeroAttackTask.Any(this, targetsForHero[i], skipPrePhase));

				if ((ignoresTaunt ? OpHeroAttackable() : isOpHeroValidAttackTarget) && !hero.CantAttackHeroes)
					allOptions.Add(HeroAttackTask.Any(this, Opponent.Hero, skipPrePhase));
			}
			#endregion

			return allOptions;

			#region local functions
			void GetPlayCardTasks(in IPlayable playable, in IPlayable chooseOnePlayable = null, int subOption = -1)
			{
				Card card = chooseOnePlayable?.Card ?? playable.Card;

				if (!spellCostHealth.HasValue)
					spellCostHealth = ControllerAuraEffects[GameTag.SPELLS_COST_HEALTH] == 1;

				bool healthCost = (playable.AuraEffects?.CardCostHealth ?? false) || Playable.CostsHealth(playable) || // HsServer
				                  (spellCostHealth.Value && playable.Card.Type == CardType.SPELL);

				if (!healthCost && Playable.CostsCorpses(playable)) // HsServer: costs Corpses instead of Mana
				{
					if (playable.Cost > Corpses) return;
					healthCost = true;
				}
				if (!healthCost && Playable.CostsOpponentHealth(playable)) // HsServer: costs the opponent's Health (Agamaggan)
				{
					if (playable.Cost > this[HsTag.NEXT_CARD_COSTS_OPPONENT_HEALTH]) return;
					healthCost = true;
				}
				if (!healthCost && (playable.Cost > mana || playable.Card.HideStat))
					return;

				// check PlayableByPlayer
				switch (playable.Card.Type)
				{
					//	REQ_MINION_CAP
					case CardType.MINION when BoardZone.IsFull && !Actions.Generic.MagneticOntoFullBoard(this, card):
						return;
					// HsServer: a Location takes a board slot; its card's targeting is for activating it, not for playing it
					case CardType.LOCATION when BoardZone.IsFull:
						return;
					case CardType.LOCATION:
						for (int i = 0; i <= zonePosRange; i++)
						{
							if (!MinionSlotOk(playable, i)) continue;
							allOptions.Add(PlayCardTask.Any(this, playable, null, i, subOption, skipPrePhase));
						}
						return;
					case CardType.SPELL:
					{
						if (card.IsSecret)
						{
							if (SecretZone.IsFull) // REQ_SECRET_CAP
								return;
							if (SecretZone.Any(p => p.Card.AssetId == card.AssetId)) // REQ_UNIQUE_SECRET
								return;
						}

						if (card.IsQuest && (SecretZone.Quest != null || SecretZone.IsFull))
							return;
						// HsServer (2026-10-08): "You can only have one copy of each Sidequest in play at once" (wiki Sidequest.txt:13)
						if (card[GameTag.SIDEQUEST] > 0 && SecretZone.Any(p => p.Card.AssetId == card.AssetId))
							return;
						if (card[GameTag.SIDEQUEST] > 0 && SecretZone.IsFull) // HsServer: Sidequests use a hero-zone slot too
							return;
						break;
					}
				}

				{
					if (!card.IsPlayableByCardReq(this))
						return;

					// HsServer: a card that targets a card in hand (Power.HandTarget) offers each valid hand card (and its
					// characters, if it also targets the board); with none valid it plays without a target (below).
					List<IPlayable> handTargets = (chooseOnePlayable ?? playable).HandTargets();
					if (handTargets != null && handTargets.Count > 0)
					{
						Character[] alsoBoard = GetTargets(card);
						var entities = new List<IPlayable>(handTargets);
						if (alsoBoard != null) entities.AddRange(alsoBoard);
						foreach (IPlayable target in entities)
							if (playable is Minion)
								for (int i = 0; i <= zonePosRange; i++)
								{
									if (!MinionSlotOk(playable, i)) continue;
									allOptions.Add(PlayCardTask.Any(this, playable, target, i, subOption, skipPrePhase));
								}
							else
								allOptions.Add(PlayCardTask.Any(this, playable, target, -1, subOption, skipPrePhase));
						return;
					}

					// HsServer (WILD_WEST): no targets while the card's target-replacing bonus is on (Actions.Generic.DropsTarget)
					Character[] targets = Actions.Generic.DropsTarget(chooseOnePlayable ?? playable) ? null
						: chooseOnePlayable == null && playable is Playable both && both.RunsBothOptions ? CombinedTargets(both)
						// HsServer (livecheck 2026-10-10): a card that carries another card's play requirements (ADDITIONAL_PLAY_REQS_1/2:
						// Bashana's Treant, the Drustvar Horror text) offers that card's targets (Playable.TargetingCard)
						: GetTargets(chooseOnePlayable == null && playable is Playable carrier ? carrier.TargetingCard : card);

					// Card doesn't require any targets
					if (targets == null)
					{
						if (playable is Minion)
							for (int i = 0; i <= zonePosRange; i++)
							{
								if (!MinionSlotOk(playable, i)) continue;
								allOptions.Add(PlayCardTask.Any(this, playable, null, i, subOption, skipPrePhase));
							}
						else
							allOptions.Add(PlayCardTask.Any(this, playable, null, -1, subOption, skipPrePhase));
					}
					else
					{
						if (targets.Length == 0)
						{
							if (card.MustHaveTargetToPlay || chooseOnePlayable == null && playable is Playable carrier2 && carrier2.MustHaveTarget)
								return;

							if (playable is Minion)
								for (int i = 0; i <= zonePosRange; i++)
								{
									if (!MinionSlotOk(playable, i)) continue;
									allOptions.Add(PlayCardTask.Any(this, playable, null, i, subOption, skipPrePhase));
								}
							else
								allOptions.Add(PlayCardTask.Any(this, playable, null, -1, subOption, skipPrePhase));
						}
						else
						{
							for (int j = 0; j < targets.Length; j++)
							{
								ICharacter target = targets[j];
								if (playable is Minion)
									for (int i = 0; i <= zonePosRange; i++)
									{
										if (!MinionSlotOk(playable, i)) continue;
										allOptions.Add(PlayCardTask.Any(this, playable, target, i, subOption,
											true));
									}
								else
									allOptions.Add(PlayCardTask.Any(this, playable, target, -1, subOption, skipPrePhase));

							}
						}
					}
				}
			}

			// HsServer: a Choose One card with both effects combined offers every target one of its options takes (wiki Fandral
			// Staghelm: "Choose One cards with targeted effects will use the same target for both effects"); null: no option targets
			Character[] CombinedTargets(Playable both)
			{
				List<Character> union = null;
				foreach (IPlayable option in both.ChooseOnePlayables)
				{
					Character[] of = GetTargets(option.Card);
					if (of == null) continue;
					union ??= new List<Character>();
					foreach (Character t in of)
						if (!union.Contains(t)) union.Add(t);
				}
				return union?.ToArray();
			}

			// Returns null if targeting is not required
			// Returns 0 Array if there is no available target
			Character[] GetTargets(Card card)
			{
				// Check it needs additional validation
				if (!card.TargetingAvailabilityPredicate?.Invoke(this, card) ?? false)
					return null;

				Character[] targets;

				switch (card.TargetingType)
				{
					case TargetingType.None:
						return null;
					case TargetingType.All:
						if (allTargets == null)
						{
							if (Opponent.Hero.HasStealth)
							{
								allTargets = new Character[GetFriendlyMinions().Length + GetEnemyMinions().Length + 1];
								allTargets[0] = Hero;
								Array.Copy(GetAllMinions(), 0, allTargets, 1, allMinions.Length);
							}
							else
							{
								allTargets = new Character[GetFriendlyMinions().Length + GetEnemyMinions().Length + 2];
								allTargets[0] = Hero;
								allTargets[1] = Opponent.Hero;
								Array.Copy(GetAllMinions(), 0, allTargets, 2, allMinions.Length);
							}
						}
						targets = allTargets;
						break;
					case TargetingType.FriendlyCharacters:
						if (allFriendly == null)
						{
							allFriendly = new Character[GetFriendlyMinions().Length + 1];
							allFriendly[0] = Hero;
							Array.Copy(friendlyMinions, 0, allFriendly, 1, friendlyMinions.Length);
						}
						targets = allFriendly;
						break;
					case TargetingType.EnemyCharacters:
						if (allEnemies == null)
						{
							if (!Opponent.Hero.HasStealth)
							{
								allEnemies = new Character[GetEnemyMinions().Length + 1];
								allEnemies[0] = Opponent.Hero;
								Array.Copy(enemyMinions, 0, allEnemies, 1, enemyMinions.Length);
							}
							else
								allEnemies = GetEnemyMinions();
						}
						targets = allEnemies;
						break;
					case TargetingType.AllMinions:
						targets = GetAllMinions();
						break;
					case TargetingType.FriendlyMinions:
						targets = GetFriendlyMinions();
						break;
					case TargetingType.EnemyMinions:
						targets = GetEnemyMinions();
						break;
					case TargetingType.Heroes:
						targets = !Opponent.Hero.HasStealth
							? new[] { Hero, Opponent.Hero }
							: new[] { Hero };
						break;
					default:
						throw new ArgumentOutOfRangeException();
				}

				// Filtering for target_if_available
				TargetingPredicate p = card.TargetingPredicate;
				if (p != null)
				{
					if (card.Type == CardType.SPELL || card.Type == CardType.HERO_POWER)
					{
						Character[] buffer = new Character[targets.Length];
						int i = 0;
						for (int j = 0; j < targets.Length; ++j)
						{
							if (!p(targets[j]) || targets[j].CantBeTargetedBySpells) continue;
							buffer[i] = targets[j];
							i++;
						}

						if (i != targets.Length)
						{
							Character[] result = new Character[i];
							Array.Copy(buffer, result, i);
							return result;
						}
						return buffer;
					}
					else
					{
						if (!card.TargetingAvailabilityPredicate?.Invoke(this, card) ?? false)
							return null;

						Character[] buffer = new Character[targets.Length];
						int i = 0;
						for (int j = 0; j < targets.Length; ++j)
						{
							if (!p(targets[j])) continue;
							buffer[i] = targets[j];
							i++;
						}

						if (i != targets.Length)
						{
							Character[] result = new Character[i];
							Array.Copy(buffer, result, i);
							return result;
						}
						return buffer;
					}
				}
				else if (card.Type == CardType.SPELL || card.Type == CardType.HERO_POWER)
				{
					Character[] buffer = new Character[targets.Length];
					int i = 0;
					for (int j = 0; j < targets.Length; ++j)
					{
						if (targets[j].CantBeTargetedBySpells) continue;
						buffer[i] = targets[j];
						i++;
					}

					if (i != targets.Length)
					{
						Character[] result = new Character[i];
						Array.Copy(buffer, result, i);
						return result;
					}
					return buffer;
				}

				return targets;

				Minion[] GetFriendlyMinions()
				{
					return friendlyMinions ?? (friendlyMinions = BoardZone.GetAll());
				}

				Minion[] GetAllMinions()
				{
					if (allMinions != null)
						return allMinions;

					allMinions = new Minion[GetEnemyMinions().Length + GetFriendlyMinions().Length];
					Array.Copy(enemyMinions, allMinions, enemyMinions.Length);
					Array.Copy(friendlyMinions, 0, allMinions, enemyMinions.Length, friendlyMinions.Length);

					return allMinions;
				}
			}

			void GenerateAttackTargets()
			{
				if (attackTargets != null) return;

				Minion[] eMinions = GetEnemyMinions();
				//var taunts = new Minion[eMinions.Length];
				Minion[] taunts = null;
				int tCount = 0;
				for (int i = 0; i < eMinions.Length; i++)
					if (eMinions[i].HasTaunt)
					{
						if (taunts == null)
							taunts = new Minion[eMinions.Length];
						taunts[tCount] = eMinions[i];
						tCount++;
					}

				if (tCount > 0)
				{
					var targets = new Minion[tCount];
					Array.Copy(taunts, targets, tCount);
					attackTargets = targets;
					isOpHeroValidAttackTarget = false;  // some brawls allow taunt heros and this should be fixed
					return;
				}
				attackTargets = eMinions;

				isOpHeroValidAttackTarget =
					!Opponent.Hero.IsImmune && !Opponent.Hero.HasStealth;
			}

			bool OpHeroAttackable() => !Opponent.Hero.IsImmune && !Opponent.Hero.HasStealth;

			Minion[] GetEnemyMinions()
			{
				return enemyMinions ?? (enemyMinions = Opponent.BoardZone.GetAll(p => !p.HasStealth && !p.IsImmune));
			}
			#endregion
		}

		/// <summary>
		/// Returns a string which dumps information about this player.
		/// </summary>
		/// <returns></returns>
		public string FullPrint()
		{
			var str = new StringBuilder();
			str.Append($"{Name}[Mana:{RemainingMana}/{OverloadOwed}/{BaseMana}][{OverloadLocked}]");
			//str.Append($"[ENCH {OldEnchants.Count}]");
			//str.Append($"[TRIG {Triggers.Count}]");
			return str.ToString();
		}

	internal class CardContainer : IEnumerable<Card>
	{
		/// <summary>The cards container</summary>
		/// <autogeneratedoc />
		internal Dictionary<string, Card> Cards { get; private set; }

		/// <summary>Gets the <see cref="Card"/> with the specified card identifier.</summary>
		/// <value>The <see cref="Card"/>.</value>
		/// <param name="cardId">The card identifier.</param>
		/// <returns></returns>
		/// <autogeneratedoc />
		internal Card this[string cardId] => Cards[cardId];

		internal void Load(IEnumerable<Card> cards)
		{
			// Set cards (without behaviours)
			Cards = (from c in cards select new { Key = c.Id, Value = c }).ToDictionary(x => x.Key, x => x.Value);

			// HsServer (2026-10-07): a client card a script defines is loaded even when ReprintCards.Build's naming rules left
			// it out (TTN_02t30e1, named after no card): the script naming its id is the reason (ReprintCards.ScriptedClientCard).
			foreach (string id in CardDefs.Instance.Get.Keys)
				if (!Cards.ContainsKey(id) && ReprintCards.ScriptedClientCard(id) is Card scripted)
					Cards[id] = scripted;

			// HsServer: hero-skin hero powers borrow the definition of the scripted power they match (see ReprintCards).
			ReprintCards.MapHeroPowerVariants(id => CardDefs.Instance.Get.ContainsKey(id));

			// Add Powers
			foreach (Card c in Cards.Values)
			{
				// HsServer: reprints use the original card's definition (same text, see ReprintCards).
				if (CardDefs.Instance.Get.TryGetValue(c.Id, out CardDef cardDef) ||
				    ReprintCards.CanonicalOf.TryGetValue(c.Id, out string canonicalId) && CardDefs.Instance.Get.TryGetValue(canonicalId, out cardDef)
				    // HsServer (WONDERS): a "counts as a copy" reprint (tag 858) never plays an original's stale 2021 script (its text
				    // changed since and no HsServer script replaced it): it stays a placeholder until the original is updated
				    && !(ReprintCards.IsCopyReprint(c.Id) && ReprintCards.IsStaleScript(canonicalId) && !CardDefs.HsServerIds.Contains(canonicalId)))
				{
					// fill missing entourage, last card def with info is CardDefs-36393.xml
					// (HsServer: before the play requirements, which may check it — e.g. a skin's Totemic Call)
					if (cardDef.Entourage != null)
					{
						c.Entourage = cardDef.Entourage;
					}

					// fill missing playrequirements, last card def with info is CardDefs-36393.xml
					if (cardDef.PlayReqs != null)
					{
						c.SetPlayRequirements(cardDef.PlayReqs);
					}

					c.Power = cardDef.Power;
					// HsServer (TITANS review): a play requirement the script states (Power.PlayableIf)
					if (cardDef.Power?.PlayableIf is { } playableIf)
					{
						System.Func<Model.Entities.Controller, bool> check = playableIf.Check;
						c.AddScriptPlayCheck(playableIf.Error, (ctl, card) => check(ctl));
					}
					c.Implemented = cardDef.Power == null ||
									cardDef.Power.PowerTask != null ||
									cardDef.Power.DeathrattleTask != null ||
									cardDef.Power.ComboTask != null ||
									cardDef.Power.TopdeckTask != null ||
									cardDef.Power.OverkillTask != null ||
									cardDef.Power.Aura != null ||
									cardDef.Power.Trigger != null ||
									cardDef.Power.Enchant != null ||
									cardDef.Power.AwakenTask != null || // HsServer: a Dormant card's whole effect (Imprisoned Observer)
									cardDef.Power.BoardVersion != null ||  // HsServer: a card that becomes its board's version (Transfer Student)
									cardDef.Power.TradeTask != null || // HsServer: "After you Trade this" (Blackwater Cutlass)
									cardDef.Power.HonorableKillTask != null || // HsServer: Honorable Kill
									cardDef.Power.CorruptTask != null || cardDef.Power.NoScript ||
									cardDef.Power.AttackInstead != null || // HsServer: "… attack instead" (Neptulon)
									cardDef.Power.SummonInsteadOfTransform || // HsServer: Baroness Vashj
									cardDef.Power.GivenDeathrattlesTwice || // HsServer: Scourge Troll
									cardDef.Power.TransformCostsMore > 0 || cardDef.Power.CopiesDarkGifts || // HsServer: Plucky Podling, Wallow
									cardDef.Power.AttacksHealedEnemy || // HsServer: Wilted Shadow
									cardDef.Power.InteractTask != null || // HsServer: the Underfel Rift
									cardDef.Power.WhenSummonedTask != null || // HsServer: "When summoned, ..." (CATACLYSM limbs, Soldiers)
									cardDef.Power.ExtraDamageTaken != 0 || cardDef.Power.HealthLossToMaxHealth != null || // HsServer (CATACLYSM)
									cardDef.Power.AdjacentInHand != null || cardDef.Power.HandTransform != null ||
									cardDef.Power.ManaSpentWhileHeld || cardDef.Power.LastManaSpentTask != null || cardDef.Power.CopiesLimbGains != null ||
									cardDef.Power.AdjacentOnBoard != null || cardDef.Power.AfterShatterTask != null || cardDef.Power.AfterPrepareTask != null || cardDef.Power.HeroDamageShuffles != null || cardDef.Power.ExtraOnStatGain != null || cardDef.Power.AlwaysGoSecond || cardDef.Power.CannoneerShot != null || cardDef.Power.CorpsesGainedTask != null ||
									cardDef.Power.CorpseSpentTask != null || // HsServer: improves / progresses as Corpses are spent
									cardDef.Power.CostsHealthWhile != null || // HsServer: "Costs Health instead of Mana" (Blood Treant)
									cardDef.Power.SideboardTask != null || // HsServer: a deck-building effect (Commander Beatrix)
									cardDef.Power.SecondPowerTask != null || // HsServer: a second POWER block (the Riffs)
									cardDef.Power.TitanAbilityTask != null || // HsServer (TITANS): "After this uses an ability"
									cardDef.Power.FollowsCthunGains || // HsServer (WONDERS): Eyestalk of C'Thun
									cardDef.Power.HeroPowerBuffInstead != null || // HsServer (WONDERS): Poisoned Blade
									cardDef.Power.StateCheck != null || // HsServer (WILD_WEST): "Whenever your hand has less than 3 cards" (Howdyfin)
									cardDef.Power.LaunchTask != null || cardDef.Power.CollidesWith != null || // HsServer (SPACE)
									cardDef.Power.PlayableIf != null; // HsServer (token pass): a card that only can't be played (Fortune VAC_420t, Slice of Bread VAC_525t1)
				}
			}

			// HsServer (WHIZBANG): a Mini / Gigantic (client MINI 3319 / GIGANTIC 3400) without its own script plays the script of the card
			// whose on-play replacement it is (wiki Miniaturize: "a 1-Cost 1/1 copy of this" — the same text)
			var byDbf = Cards.Values.GroupBy(x => x.AssetId).ToDictionary(x => x.Key, x => x.First());
			foreach ((int from, int to) in Model.Cards.OnPlayReplacementRows())
				if (byDbf.TryGetValue(to, out Card sized) && byDbf.TryGetValue(from, out Card original) && sized.Power == null && original.Power != null &&
				    (sized[(Enums.GameTag)3319] > 0 || sized[(Enums.GameTag)3400] > 0) && !CardDefs.Instance.Get.ContainsKey(sized.Id))
				{
					sized.Power = original.Power;
					if (CardDefs.Instance.Get.TryGetValue(original.Id, out CardDef originalDef) && originalDef.PlayReqs != null)
						sized.SetPlayRequirements(originalDef.PlayReqs);
					sized.Implemented = original.Implemented;
				}

			// HsServer: a card whose text is only keywords works from its tags alone (no script needed).
			foreach (Card c in Cards.Values)
				if (!c.Implemented && ReprintCards.DbfDirectory != null && ReprintCards.IsKeywordOnly(c.Text))
					c.Implemented = true;

			// HsServer (token pass 2026-10-09): a Starship (client STARSHIP without STARSHIP_PIECE: The Exile's Hope GDB_100t2,
			// Battlecruiser SC_999t) is built by the mechanic from its pieces — their stats, keywords and launch effects
			// (Actions/Starship.cs: StarshipCardFor, RunLaunchEffects); it has no effect of its own.
			foreach (Card c in Cards.Values)
				if (!c.Implemented && c.Type == Enums.CardType.MINION && c[Actions.Generic.STARSHIP] > 0 && c[Actions.Generic.STARSHIP_PIECE] == 0)
					c.Implemented = true;

			// HsServer (token pass 2026-10-09): the same card printed again under another id — the client's name, card type and current
			// text equal a scripted card's — plays with that card's script when it has none of its own: Lightforged Zealot's Truesilver
			// Champion DRG_232t = CS2_097, Toxic Reinforcements' Leper Gnome DRG_255t2 = EX1_029, the Healing Totem AT_132_SHAMANa =
			// NEW1_009, Evolve TB_OG_027 = OG_027. ReprintCards.Build does this for client-only tokens (Kazakusan's Treasures); these
			// were in SabberStone's 2021 data with an empty placeholder script, so that rule never saw them.
			ShareScriptsOfSameCards();

			// HsServer (TITANS review 2026-10-07): a Choose One card whose options are all scripted works through them
			// (Playable.ActivateTask runs the chosen option, or both): it is implemented, so random casts and generation pools
			// that ask for implemented cards find it (live-20261005/140614 40099: a random cast made Lifebinder's Gift TTN_955,
			// which has no script of its own). The same test as the coverage tool's (CardCoverage.IsImplemented).
			foreach (Card c in Cards.Values)
				if (!c.Implemented && c.ChooseOne && Model.Cards.ChooseOneOptions(c) is Card[] options && options.Length >= 2 &&
				    System.Array.TrueForAll(options, o => o.Implemented))
					c.Implemented = true;

			MagnetizeEnchantmentsFromData();
		}

		/// <summary>
		/// HsServer (TITANS): a magnetize enchantment (a MODULAR enchantment; its 853 names its Magnetic minion, whose 2787 names it
		/// back) with no script of its own works from the client data — wiki Magnetic: the Mech gets "its stats and text (other
		/// than Magnetic)": the minion's Attack / Health (its script tags, Generic.Magnetize), the keywords of its text
		/// (Enchants.GetAutoEnchantFromText: Sparkbots, Absorbent Parasite), "Stealth for 1 turn" leaving at its owner's next turn
		/// (SP-3Y3-D3R), the minion's Deathrattle (Containment Unit); its triggers come with the minion (Generic.Magnetize).
		/// A script's own definition wins.
		/// </summary>
		/// <summary>
		/// HsServer (token pass 2026-10-09): an unscripted card (no HsServer definition, no effect) whose client name, card type and
		/// current client text are a scripted card's takes that card's script and play requirements (see the call in Load). The
		/// first such card by id wins; client text compared without markup (ReprintCards.SameClientText).
		/// </summary>
		private void ShareScriptsOfSameCards()
		{
			if (ReprintCards.DbfDirectory == null) return;
			var scripted = Cards.Values.Where(c => c.Implemented && c.Power != null && c.Name != null && ReprintCards.ClientText(c.Id) != null)
				.GroupBy(c => (c.Name, c.Type))
				.ToDictionary(g => g.Key, g => g.OrderBy(c => c.Id, StringComparer.Ordinal).ToList());
			foreach (Card c in Cards.Values.OrderBy(c => c.Id, StringComparer.Ordinal))
			{
				if (c.Implemented || c.Name == null || CardDefs.HsServerIds.Contains(c.Id) || string.IsNullOrEmpty(ReprintCards.ClientText(c.Id)))
					continue;
				if (!scripted.TryGetValue((c.Name, c.Type), out List<Card> twins)) continue;
				Card twin = twins.FirstOrDefault(x => x.Id != c.Id && ReprintCards.SameClientText(x.Id, c.Id));
				if (twin == null) continue;
				c.Power = twin.Power;
				if (twin.PlayRequirements != null && twin.PlayRequirements.Count > 0)
					c.SetPlayRequirements(new Dictionary<Enums.PlayReq, int>(twin.PlayRequirements));
				if (c.Entourage == null || c.Entourage.Length == 0) c.Entourage = twin.Entourage;
				c.Implemented = true;
			}
		}

		private void MagnetizeEnchantmentsFromData()
		{
			var byDbf = new Dictionary<int, Card>();
			foreach (Card c in Cards.Values)
				if (!byDbf.ContainsKey(c.AssetId)) byDbf[c.AssetId] = c;
			foreach (Card c in Cards.Values)
			{
				if (c.Type != Enums.CardType.ENCHANTMENT || !c.Modular || c.Power != null) continue;
				byDbf.TryGetValue(c[(Enums.GameTag)853], out Card minion);
				bool oneTurnStealth = (c.Text ?? "").Contains("<b>Stealth</b> for 1 turn");
				c.Power = new Enchants.Power
				{
					Enchant = WithMinionKeywords(Enchants.Enchants.GetAutoEnchantFromText(c), minion),
					DeathrattleTask = minion?.Type == Enums.CardType.MINION ? minion.Power?.DeathrattleTask : null,
					Trigger = oneTurnStealth
						? new Triggers.Trigger(Enums.TriggerType.TURN_START) { SingleTask = Tasks.SimpleTasks.RemoveEnchantmentTask.Task, RemoveAfterTriggered = true }
						: null,
				};
				c.Implemented = true;
			}
		}

		/// <summary>
		/// HsServer (WILD_WEST): a magnetize enchantment whose text names no keyword ("Increased stats.": Prosthetic Hand's DEEP_015e)
		/// carries its Magnetic minion's own keywords (the minion card's ability tags after load, Magnetic itself excepted) — wiki
		/// Magnetic: the Mech gets "its stats and text (other than Magnetic)"; Prosthetic Hand's text is "Magnetic, Reborn". The
		/// other magnetize enchantments name theirs (BOT_911e "Taunt, Divine Shield.": GetAutoEnchantFromText). DOUBT (unrecorded).
		/// </summary>
		private static Enchants.Enchant WithMinionKeywords(Enchants.Enchant enchant, Card minion)
		{
			if (enchant == null || minion?.Type != Enums.CardType.MINION || enchant.Effects.Length > 2) return enchant;
			var extra = new List<Enchants.IEffect>();
			void Add(Enums.GameTag tag) => extra.Add(new Enchants.Effect(tag, Enchants.EffectOperator.SET, 1));
			if (minion.Taunt) Add(Enums.GameTag.TAUNT);
			if (minion.DivineShield) Add(Enums.GameTag.DIVINE_SHIELD);
			if (minion.Windfury) Add(Enums.GameTag.WINDFURY);
			if (minion.Charge) Add(Enums.GameTag.CHARGE);
			if (minion.Poisonous) Add(Enums.GameTag.POISONOUS);
			if (minion.LifeSteal) Add(Enums.GameTag.LIFESTEAL);
			if (minion[Enums.GameTag.RUSH] > 0) Add(Enums.GameTag.RUSH);
			if (minion[Enums.GameTag.REBORN] > 0) Add(Enums.GameTag.REBORN);
			if (minion[Enums.GameTag.STEALTH] > 0) Add(Enums.GameTag.STEALTH);
			if (minion[Enums.GameTag.CANT_BE_TARGETED_BY_SPELLS] > 0 && minion[Enums.GameTag.CANT_BE_TARGETED_BY_HERO_POWERS] > 0)
			{
				Add(Enums.GameTag.CANT_BE_TARGETED_BY_SPELLS);
				Add(Enums.GameTag.CANT_BE_TARGETED_BY_HERO_POWERS);
			}
			if (extra.Count == 0) return enchant;
			return new Enchants.Enchant(enchant.Effects.Concat(extra).ToArray())
			{
				UseScriptTag = enchant.UseScriptTag, IsOneTurnEffect = enchant.IsOneTurnEffect, RemoveWhenPlayed = enchant.RemoveWhenPlayed
			};
		}

		/// <summary>Returns an enumerator that iterates through the collection.</summary>
		/// <returns>An enumerator that can be used to iterate through the collection.</returns>
		/// <autogeneratedoc />
		public IEnumerator<Card> GetEnumerator()
		{
			return Cards.Values.GetEnumerator();
		}

		/// <summary>Returns an enumerator that iterates through a collection.</summary>
		/// <returns>
		/// An <see cref="T:System.Collections.IEnumerator" /> object that can be used to iterate through the collection.
		/// </returns>
		/// <autogeneratedoc />
		IEnumerator IEnumerable.GetEnumerator()
		{
			return GetEnumerator();
		}

	}

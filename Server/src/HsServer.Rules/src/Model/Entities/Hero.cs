		}

		/// <summary>HsServer: the fatigue count lives on the player (live: TAG_CHANGE Player FATIGUE=n), so it survives a hero change.</summary>
		public int Fatigue
		{
			get { return Controller[GameTag.FATIGUE]; }
			set { Controller[GameTag.FATIGUE] = value; }
		}

		public int DamageTakenThisTurn { get; set; }

		public override bool CantAttackHeroes
		{
			get
			{
				if (AuraEffects?.CannotAttackHeroes ?? false)
					return true;
				// HsServer: a weapon that "Can't attack heroes" (Lightbringer's Hammer)
				if (Weapon != null && Weapon[GameTag.CANNOT_ATTACK_HEROES] > 0)
					return true;
				// HsServer: an extra attack only against minions (Multi-Strike: "may attack an additional enemy minion")
				if (this[HsTag.EXTRA_ATTACK_MINIONS_ONLY] > 0 && NumAttacksThisTurn >= 1)
					return true;

				return base.CantAttackHeroes;
			}
			set => base.CantAttackHeroes = value;
		}

		private int _extraAttacksThisTurn;

		public int ExtraAttacksThisTurn
		{
			get => _extraAttacksThisTurn;
			set
			{
				_extraAttacksThisTurn = value;
				if (_history)
					this[GameTag.EXTRA_ATTACKS_THIS_TURN] = value;
			}
		}

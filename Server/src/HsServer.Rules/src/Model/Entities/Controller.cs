		public override int this[GameTag t]
		{
			get
			{
				_data.TryGetValue(t, out int value);
				return value + ControllerAuraEffects[t];
			}
			set
			{
				// HsServer: locked (overloaded) crystals are part of the spent mana (live RESOURCES_USED): any change of
				// OVERLOAD_LOCKED — a script's tag task too (Lava Shock unlocks) — moves the spent mana with it, first.
				if (t == GameTag.OVERLOAD_LOCKED && !_settingLockedRaw)
				{
					_data.TryGetValue(GameTag.OVERLOAD_LOCKED, out int locked);
					if (value != locked)
						UsedMana = Math.Max(0, UsedMana + value - locked);
				}
				if (_logging)
					Game.Log(LogLevel.DEBUG, BlockType.TRIGGER, "Entity", !Game.Logging ? "" : $"{this} set data {t} to {value}");
				if (_history && Entity.InHistory(t))
					if (value + ControllerAuraEffects[t] != this[t])
						Game.PowerHistory.Add(PowerHistoryBuilder.TagChange(Id, t, value));

				_data[t] = value;
			}
		}


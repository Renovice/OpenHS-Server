		public void AddWeapon(Weapon weapon)
		{
			// HsServer: the replaced weapon remembers what replaced it (Instrument Smasher; HsTag.REPLACED_BY_WEAPON)
			if (Weapon != null && weapon != null && Weapon != weapon)
				Weapon[Enums.HsTag.REPLACED_BY_WEAPON] = weapon.Id;
			RemoveWeapon();
			weapon.OrderOfPlay = Game.NextOop;
			Weapon = weapon;
			Weapon[GameTag.ZONE] = (int)Enums.Zone.PLAY;
			Weapon[GameTag.ZONE_POSITION] = 0;
			EquippedWeapon = weapon.Id;
			// HsServer: live — a hero with a Windfury weapon has WINDFURY itself (Doomhammer: hero WINDFURY 1), until it's gone
			if (weapon.IsWindfury)
				this[GameTag.WINDFURY] = 1;
			if (weapon.IsWindfury && IsExhausted && NumAttacksThisTurn == 1)
				IsExhausted = false;

			// HsServer (2026-11-20): a weapon aura already in play reaches a weapon equipped later ("Your Crabatoa Claws have +2 Attack":
			// the Claw a dying Claw equips — live session-20261120-132514 36655), like a board aura reaches a minion summoned later
			foreach (IAura a in Game.Auras)
				foreach (IAura part in a is MultiAura multi ? (IEnumerable<IAura>)multi : new[] { a })
					if (part is Aura weaponAura && weaponAura.Type == AuraType.WEAPON && weaponAura.Owner?.Controller == Controller)
						weaponAura.EntityAdded(weapon);

			Game.RaiseEvent(() => Game.TriggerManager.OnEquipWeaponTrigger(weapon));
		}

		/// <summary>
		/// Removes the equipped weapon to the graveyard. This triggers deathrattle events on the weapon.
		/// </summary>
		public void RemoveWeapon()
		{
			if (Weapon == null)
				return;

			if (Weapon.HasDeathrattle)
				for (int times = Controller.DeathrattleTimes(Weapon); times > 0; times--)
					Weapon.ActivateTask(PowerActivation.DEATHRATTLE);

			Game.TriggerManager.OnDeathTrigger(Weapon);

			Game.Log(LogLevel.INFO, BlockType.PLAY, "Hero", !Game.Logging? "":$"Butcher's knife incoming to graveyard, say 'gugus' to {Weapon}");
			Controller.GraveyardZone.Add(Weapon);
			Controller.DiedThisGame.Add(Weapon.Id); // HsServer: a destroyed weapon "died this game" (Rummaging Kobold)

			ClearWeapon();
		}

		/// <summary>
		/// Clears weapon information on Hero.
		/// </summary>
		public void ClearWeapon()
		{
			Weapon.ActivatedTrigger?.Remove();
			Weapon.OngoingEffect?.Remove();
			if (Weapon.AppliedEnchantments != null && Weapon[GameTag.KEEP_ENCHANTMENTS] != 1)
				for (int i = Weapon.AppliedEnchantments.Count - 1; i >= 0; i--)
					Weapon.AppliedEnchantments[i].Remove();
			if (Weapon.IsWindfury && this[GameTag.WINDFURY] != 0)
				this[GameTag.WINDFURY] = 0;
			Weapon = null;
			EquippedWeapon = 0;
			// HsServer (2026-10-08): the attacks it made count against the next weapon too (wiki Windfury.txt:14; RefreshAttackReady)
			Actions.Generic.RefreshAttackReady(this);
		}

		public override IPlayable Clone(in Controller controller)
		{
			return new Hero(in controller, this);
		}

		public string FullPrint()
		{
			var str = new StringBuilder();
			string mStr = Weapon != null ? $"[{Weapon.Card.Name}[{Weapon.AttackDamage}/{Weapon.Durability}]]" : "[NO WEAPON]";
			str.Append($"[HERO][{this}][ATK{AttackDamage}/AR{Armor}/HP{Health}][WP{mStr}][SP{Controller.CurrentSpellPower}]");
			//str.Append($"[ENCH {OldEnchants.Count}]");
			//str.Append($"[TRIG {Triggers.Count}]");
			return str.ToString();
		}


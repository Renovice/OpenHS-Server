		/// <summary>
		/// HsServer: a minion that gains Rush in play during its owner's turn before attacking may attack minions now (wiki Rush:
		/// "can attack minions on the turn it is summoned"), whatever gave it — a tag (Libram of Faith, Bonus Effects, Corpse
		/// drakes, Sparkler…) the same as the Rush enchantment effect (Effect.ApplyTo SET RUSH). Was only in the enchantment path:
		/// a summoned minion given the tag stayed asleep.
		/// </summary>
		public override int this[GameTag t]
		{
			get => base[t];
			set
			{
				bool gainsRush = t == GameTag.RUSH && value > 0 && !IsRush;
				bool wasUntouchable = (t == GameTag.DORMANT || t == Actions.Generic.LAUNCHPAD) && Untouchable;
				base[t] = value;
				// (the board counts its untouchables — Dormant, a Starship on its launchpad: one that stops or starts being one
				// in play is recounted; the launch left the count one too high, soak 851396 Meteor Storm)
				if ((t == GameTag.DORMANT || t == Actions.Generic.LAUNCHPAD) && wasUntouchable != Untouchable && Zone is Zones.BoardZone board)
				{
					board.RecountUntouchables();
					// HsServer (livecheck 2026-10-10): a Permanent / Dormant minion isn't a minion for "your minions" auras (rule book BE2,
					// Aura.Apply): it leaves them going Dormant and joins them awakening / launched
					// (the board's Auras are the ones that cover its minions: its owner's and the opponent's "enemy minions" ones)
					if (Untouchable) board.Auras.ForEach(a => a.EntityRemoved(this));
					else board.Auras.ForEach(a => a.EntityAdded(this));
					board.AdjacentAuras.ForEach(a => a.BoardChanged = true);
				}
				if (gainsRush && Zone?.Type == Enums.Zone.PLAY && Controller == Game.CurrentPlayer && IsExhausted && NumAttacksThisTurn == 0 && !HasCharge)
				{
					IsExhausted = false;
					AttackableByRush = true;
					if (!Game.RushMinions.Contains(Id)) Game.RushMinions.Add(Id);
				}
			}
		}

		public bool HasCharge
		{
			//get => this[GameTag.CHARGE] >= 1;
			get
			{
				if (AuraEffects?.Charge > 0)
					return true;
				if (_data.TryGetValue(Actions.Generic.NON_KEYWORD_CHARGE, out int unnamed) && unnamed > 0) // HsServer: Charge without the keyword
					return true;
				if (!_data.TryGetValue(GameTag.CHARGE, out int value))
					return Card.Charge;
				return value > 0;
			}
			set
			{
				if (value)
				{
					if (IsExhausted && NumAttacksThisTurn == 0)
						IsExhausted = false;
					this[GameTag.CHARGE] = 1;
					return;
				}

				this[GameTag.CHARGE] = 0;
			}
		}

		public bool HasDivineShield
		{
			//get { return this[GameTag.DIVINE_SHIELD] == 1; }
			get
			{
				if (!_data.TryGetValue(GameTag.DIVINE_SHIELD, out int value))
					return Card.DivineShield;
				return value > 0;
			}
			set
			{
				if (_data.ContainsKey(HsTag.SHIELD_HITS_TAKEN)) this[HsTag.SHIELD_HITS_TAKEN] = 0; // (Toreth: a new shield starts whole)
				if (!value)
				{
					bool had = this[GameTag.DIVINE_SHIELD] > 0; // (Toreth: a shield shows its hits, DIVINE_SHIELD 3)
					this[GameTag.DIVINE_SHIELD] = 0;
					if (had)
						Game.RaiseEvent(() => Game.TriggerManager.OnLoseDivineShield(this));
					return;
				}

				this[GameTag.DIVINE_SHIELD] = 1;
			}
		}


namespace HsServer.Tools;

/// <summary>
/// `HsServer golden [--update] [--card ID] [--set NAME] [--jobs N]` (2026-10-09, roadmap E3 regression safety): plays every collectible
/// card in vfxcheck's test game (its board, every way to play it, its events script; a fixed random seed) and keeps the shape of what
/// the card itself did — its own blocks and those of what it made or enchanted, entity numbers replaced by "card#n" — then compares
/// it with the last accepted run. Lists every card whose behaviour changed, with the first differing lines, so a fix that quietly
/// changes other cards shows up. --update accepts the run as the new baseline (with --card / --set: those cards only).
///   RESEARCH/golden/baseline.tsv  (tracked)  card, way, hash, line count — which cards changed
///   RESEARCH/golden/cache.txt.gz  (local)    the full shapes — what changed
///   RESEARCH/golden/last-run.md               the last comparison
/// The engine's history, not the wire (ClientStream's own changes are guarded by the tests and wirecheck).
/// </summary>
internal static class Golden
{
    private const long GameSeed = 20261009;
    private const string CardMark = "@@card\t", WayMark = "@@way\t";

    public static int Run(string[] args)
    {
        string root = Program.ProjectRoot();
        string dir = Path.Combine(root, "RESEARCH", "golden");
        bool update = false;
        string? only = null, setName = null, worker = null, outFile = null;
        int jobs = Math.Max(1, Environment.ProcessorCount / 2);
        for (int i = 0; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--update": update = true; break;
                case "--card" when i + 1 < args.Length: only = args[++i]; break;
                case "--set" when i + 1 < args.Length: setName = args[++i]; break;
                case "--jobs" when i + 1 < args.Length: jobs = Math.Max(1, int.Parse(args[++i])); break;
                case "--worker" when i + 1 < args.Length: worker = args[++i]; break;
                case "--out" when i + 1 < args.Length: outFile = args[++i]; break;
            }
        }
        Sabber.SabberEngineGame.EnsureCards(Engine.CardDb.FindDefaultDir(root));
        List<Card> cards = Cards.All.Where(Covered)
            .Where(c => only == null || string.Equals(c.Id, only, StringComparison.OrdinalIgnoreCase))
            .Where(c => setName == null || string.Equals(SetName(c), setName, StringComparison.OrdinalIgnoreCase))
            .OrderBy(c => c.Id, StringComparer.Ordinal).ToList();

        // a worker: its slice of the cards into a file (the parent merges)
        if (worker != null && outFile != null)
        {
            string[] w = worker.Split('/');
            int k = int.Parse(w[0]), n = int.Parse(w[1]);
            using var writer = new StreamWriter(outFile, false, new UTF8Encoding(false));
            foreach (Card card in cards.Where((_, idx) => idx % n == k)) Write(writer, card.Id, PlayCard(card));
            return 0;
        }

        var watch = Stopwatch.StartNew();
        Dictionary<string, CardRun> now = jobs <= 1 || cards.Count < 40 ? cards.ToDictionary(c => c.Id, PlayCard) : RunWorkers(cards, jobs, only, setName);
        Console.Error.WriteLine($"{now.Count} cards played in {watch.Elapsed.TotalSeconds:0}s");

        Directory.CreateDirectory(dir);
        string baselineFile = Path.Combine(dir, "baseline.tsv"), cacheFile = Path.Combine(dir, "cache.txt.gz");
        var baseline = ReadBaseline(baselineFile);
        var cache = ReadCache(cacheFile);

        // compare
        var changed = new List<string>();
        var report = new List<string> { "# Golden run (generated by `HsServer golden`; do not edit)", "" };
        int same = 0, added = 0;
        foreach (var (id, run) in now.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            if (!baseline.TryGetValue(id, out var old)) { added++; continue; }
            if (old.Equals(Summary(run))) { same++; continue; }
            changed.Add(id);
            report.Add($"## {id} {Cards.TryFromId(id)?.Name}");
            if (old.Status != run.Status) report.Add($"- status: {old.Status} → {run.Status}");
            int ways = Math.Max(old.Ways.Count, run.Ways.Count);
            for (int w = 0; w < ways; w++)
            {
                string? oldHash = w < old.Ways.Count ? old.Ways[w].Hash : null, newHash = w < run.Ways.Count ? Hash(run.Ways[w]) : null;
                if (oldHash == newHash) continue;
                report.Add($"- way {w}: {(oldHash == null ? "new" : newHash == null ? "gone" : "changed")}");
                if (oldHash != null && newHash != null)
                {
                    string? oldText = cache.TryGetValue(id, out var cached) && w < cached.Ways.Count ? cached.Ways[w] : null;
                    report.AddRange(oldText == null ? new[] { "  (no local copy of the old run: rerun with --update on the old build to see lines)" }
                                                     : FirstDifference(oldText, run.Ways[w]));
                }
            }
            report.Add("");
        }
        var gone = only == null && setName == null ? baseline.Keys.Where(k => !now.ContainsKey(k)).ToList() : new List<string>();
        report.Insert(2, $"{now.Count} cards: {same} same, {changed.Count} changed, {added} new, {gone.Count} gone{(baseline.Count == 0 ? " (no baseline yet)" : "")}.");
        report.Insert(3, "");
        foreach (string id in gone) report.Add($"- gone: {id}");
        File.WriteAllLines(Path.Combine(dir, "last-run.md"), report);

        bool accepted = update || baseline.Count == 0;
        if (accepted)
        {
            foreach (var (id, run) in now) { baseline[id] = Summary(run); cache[id] = run; }
            foreach (string id in gone) { baseline.Remove(id); cache.Remove(id); }
            WriteBaseline(baselineFile, baseline);
            WriteCache(cacheFile, cache);
        }
        else
        {
            // the local copy follows what the baseline accepted; a card the cache lacks gets this run's (the same hashes)
            bool grew = false;
            foreach (var (id, run) in now)
                if (!cache.ContainsKey(id) && baseline.TryGetValue(id, out var b) && b.Equals(Summary(run))) { cache[id] = run; grew = true; }
            if (grew) WriteCache(cacheFile, cache);
        }

        Console.Error.WriteLine($"{same} same, {changed.Count} changed, {added} new, {gone.Count} gone" +
                                (changed.Count > 0 ? $": {string.Join(", ", changed.Take(12))}{(changed.Count > 12 ? " ..." : "")}" : "") +
                                $" -> {Path.Combine(dir, "last-run.md")}" + (accepted ? " (baseline updated)" : ""));
        return changed.Count > 0 && !update ? 1 : 0;
    }

    /// <summary>The cards it covers: every collectible card that is played (not the hero skins).</summary>
    private static bool Covered(Card c) =>
        c.Collectible && c.Type is CardType.MINION or CardType.SPELL or CardType.WEAPON or CardType.HERO or CardType.LOCATION && !Cards.IsHeroPortrait(c);

    private static string SetName(Card c) =>
        Enum.IsDefined(typeof(Engine.TAG_CARD_SET), (int)c.Set) ? ((Engine.TAG_CARD_SET)(int)c.Set).ToString() : ((int)c.Set).ToString();

    private sealed record CardRun(string Status, List<string> Ways);

    private sealed record CardSummary(string Status, List<(string Hash, int Lines)> Ways)
    {
        public bool Equals(CardSummary? o) => o != null && Status == o.Status && Ways.SequenceEqual(o.Ways);
        public override int GetHashCode() => Status.GetHashCode();
    }

    private static CardSummary Summary(CardRun r) => new(r.Status, r.Ways.Select(w => (Hash(w), w.Count(ch => ch == '\n'))).ToList());

    private static string Hash(string text) => Convert.ToHexString(SHA1.HashData(Encoding.UTF8.GetBytes(text)))[..16].ToLowerInvariant();

    /// <summary>Plays the card every way vfxcheck does (fixed seed); each way's shape.</summary>
    private static CardRun PlayCard(Card card)
    {
        var ways = new SortedDictionary<int, string>();
        VfxCheck.Seed = GameSeed;
        VfxCheck.Played = (c, way, g, p, start) => ways[way] = Shape(g, p, start);
        string status;
        try { status = VfxCheck.PlayAll(card, new HashSet<string>()); }
        catch (Exception e) { status = "error " + e.GetType().Name; }
        finally { VfxCheck.Played = null; }
        return new CardRun(status, ways.Values.ToList());
    }

    // tags whose value is an entity (normalized like the entities): these, and every tag the client's own names mark as one
    // (…_ENTITY, …_ENTITY_ID, TAG_SCRIPT_DATA_ENT_n, CARDTEXT_ENTITY_n)
    private static readonly HashSet<GameTag> EntityTags = new HashSet<GameTag>
    {
        GameTag.LAST_AFFECTED_BY, GameTag.PROPOSED_DEFENDER, GameTag.PROPOSED_ATTACKER, GameTag.ATTACHED, GameTag.CARD_TARGET,
        GameTag.CREATOR, GameTag.DISPLAYED_CREATOR, GameTag.LAST_CARD_PLAYED,
        (GameTag)2747, // the destroyer (Generic.Destroy)
        (GameTag)1715, // an attack's link to its source (Attack.cs)
    }.Concat(Enum.GetValues<Engine.GAME_TAG>().Where(t =>
    {
        string n = t.ToString();
        return (n.EndsWith("_ENTITY", StringComparison.Ordinal) || n.EndsWith("ENTITY_ID", StringComparison.Ordinal) ||
                n.StartsWith("TAG_SCRIPT_DATA_ENT_", StringComparison.Ordinal) ||
                n.StartsWith("CARDTEXT_ENTITY_", StringComparison.Ordinal) && !n.EndsWith("AS_NUMBERS", StringComparison.Ordinal)) &&
               !n.StartsWith("SMART_DISCOVER_DEBUG", StringComparison.Ordinal);
    }).Select(t => (GameTag)(int)t)).ToHashSet();

    /// <summary>
    /// What the card did from <paramref name="start"/>: every block whose source is the card or something it made / enchanted (and all
    /// inside it), one line per entry, entities as "card#n" in order of appearance (the game GAME, the players P1 / P2). The engine's
    /// own tags (≥ 990000) are left out: they never reach the client.
    /// </summary>
    private static string Shape(SGame g, IPlayable p, int start)
    {
        var own = new HashSet<int> { p.Id };
        var labels = new Dictionary<int, string>();
        var perCard = new Dictionary<string, int>();
        string L(int id)
        {
            switch (id)
            {
                case <= 0: return "-";
                case 1: return "GAME";
                case 2: return "P1";
                case 3: return "P2";
            }
            if (labels.TryGetValue(id, out string? l)) return l;
            string cid = g.IdEntityDic.TryGetValue(id, out IPlayable? e) ? e.Card.Id : "?";
            int k = perCard[cid] = perCard.GetValueOrDefault(cid) + 1;
            return labels[id] = cid + "#" + k;
        }
        string Value(GameTag tag, int v) =>
            EntityTags.Contains(tag) ? L(v)
            : Tag.TypedTags.TryGetValue(tag, out System.Type? t) && Enum.GetName(t, v) is string n ? n : v.ToString();

        var sb = new StringBuilder();
        var recording = new Stack<bool>();
        int depth = 0;
        void Line(string s) => sb.Append(' ', depth * 2).Append(s).Append('\n');
        var history = g.PowerHistory.Full;
        for (int i = start; i < history.Count; i++)
        {
            IPowerHistoryEntry e = history[i];
            bool rec = recording.Count > 0 && recording.Peek();
            switch (e)
            {
                case PowerHistoryBlockStart b:
                {
                    bool r = rec || own.Contains(b.Source);
                    recording.Push(r);
                    if (!r) break;
                    Line($"BLOCK {b.BlockType} src={L(b.Source)} tgt={L(b.Target)} i={b.Index}" +
                         (string.IsNullOrEmpty(b.EffectCardId) ? "" : $" fx={b.EffectCardId}") +
                         (b.TriggerKeyword != 0 ? $" kw={(GameTag)b.TriggerKeyword}" : "") + (b.ShowInHistory ? " hist" : ""));
                    depth++;
                    break;
                }
                case PowerHistoryBlockEnd:
                    if (recording.Count > 0 && recording.Pop()) { depth--; Line("END"); }
                    break;
                case PowerHistoryFullEntity { Entity: { } f }:
                {
                    if (f.Tags.TryGetValue(GameTag.CREATOR, out int creator) && own.Contains(creator) ||
                        f.Tags.TryGetValue(GameTag.ATTACHED, out int on) && own.Contains(on) && f.Tags.TryGetValue(GameTag.CREATOR, out int by) && own.Contains(by))
                        own.Add(f.Id);
                    if (!rec) break;
                    var shown = new[] { GameTag.ZONE, GameTag.CONTROLLER, GameTag.ZONE_POSITION, GameTag.CREATOR, GameTag.ATTACHED, GameTag.ATK, GameTag.HEALTH, GameTag.COST }
                        .Where(f.Tags.ContainsKey).Select(t => $"{t}={Value(t, f.Tags[t])}");
                    Line($"FULL {L(f.Id)} {string.Join(" ", shown)}");
                    break;
                }
                case PowerHistoryShowEntity { Entity: { } s } when rec:
                    Line($"SHOW {L(s.Id)}");
                    break;
                case PowerHistoryHideEntity h when rec:
                    Line($"HIDE {L(h.EntityID)} {h.Zone}");
                    break;
                case PowerHistoryChangeEntity c when rec:
                    Line($"CHANGE {L(c.Entity?.Id ?? 0)} -> {c.CardId}");
                    break;
                case PowerHistoryTagChange t when rec && (int)t.Tag < 990000:
                    Line($"TAG {L(t.EntityId)} {t.Tag} {Value(t.Tag, t.Value)}");
                    break;
                case PowerHistorySubSpellStart fx when rec:
                    Line($"FX {fx.Prefab?.Split(':')[0]} src={L(fx.Source)} tgts={string.Join(",", fx.Targets.Select(L))}");
                    depth++;
                    break;
                case PowerHistorySubSpellEnd when rec:
                    depth = Math.Max(0, depth - 1);
                    Line("FX_END");
                    break;
                case PowerHistoryMetaData m when rec:
                    Line($"META {m.Type} data={m.Data} info={string.Join(",", (m.Info ?? new List<int>()).Select(L))}");
                    break;
                case PowerHistoryShuffleDeck sh when rec:
                    Line($"SHUFFLE {sh.PlayerId}");
                    break;
            }
        }
        return sb.ToString();
    }

    private static Dictionary<string, CardRun> RunWorkers(List<Card> cards, int jobs, string? only, string? setName)
    {
        string tmp = Path.Combine(Path.GetTempPath(), "hsserver-golden-" + Environment.ProcessId);
        Directory.CreateDirectory(tmp);
        var procs = new List<Process>();
        for (int k = 0; k < jobs; k++)
        {
            var psi = new ProcessStartInfo(Environment.ProcessPath!) { UseShellExecute = false, RedirectStandardError = true, RedirectStandardOutput = true };
            psi.ArgumentList.Add("golden");
            psi.ArgumentList.Add("--worker"); psi.ArgumentList.Add($"{k}/{jobs}");
            psi.ArgumentList.Add("--out"); psi.ArgumentList.Add(Path.Combine(tmp, $"w{k}.txt"));
            if (only != null) { psi.ArgumentList.Add("--card"); psi.ArgumentList.Add(only); }
            if (setName != null) { psi.ArgumentList.Add("--set"); psi.ArgumentList.Add(setName); }
            var proc = Process.Start(psi)!;
            proc.ErrorDataReceived += (_, _) => { }; proc.OutputDataReceived += (_, _) => { };
            proc.BeginErrorReadLine(); proc.BeginOutputReadLine();
            procs.Add(proc);
        }
        foreach (Process proc in procs) proc.WaitForExit();
        var result = new Dictionary<string, CardRun>();
        for (int k = 0; k < jobs; k++)
        {
            string f = Path.Combine(tmp, $"w{k}.txt");
            if (!File.Exists(f)) throw new InvalidOperationException($"golden worker {k} wrote nothing (exit {procs[k].ExitCode})");
            foreach (var (id, run) in Parse(File.ReadLines(f))) result[id] = run;
        }
        Directory.Delete(tmp, true);
        return result;
    }

    private static void Write(TextWriter w, string id, CardRun run)
    {
        w.Write(CardMark + id + "\t" + run.Status + "\n");
        for (int k = 0; k < run.Ways.Count; k++)
        {
            w.Write(WayMark + k + "\n");
            w.Write(run.Ways[k]);
        }
    }

    private static IEnumerable<(string Id, CardRun Run)> Parse(IEnumerable<string> lines)
    {
        string? id = null, status = null;
        List<string>? ways = null;
        StringBuilder? way = null;
        foreach (string line in lines)
        {
            if (line.StartsWith(CardMark, StringComparison.Ordinal))
            {
                if (id != null) { if (way != null) ways!.Add(way.ToString()); yield return (id, new CardRun(status!, ways!)); }
                string[] p = line[CardMark.Length..].Split('\t', 2);
                (id, status, ways, way) = (p[0], p.Length > 1 ? p[1] : "", new List<string>(), null);
            }
            else if (line.StartsWith(WayMark, StringComparison.Ordinal))
            {
                if (way != null) ways!.Add(way.ToString());
                way = new StringBuilder();
            }
            else way?.Append(line).Append('\n');
        }
        if (id != null) { if (way != null) ways!.Add(way.ToString()); yield return (id, new CardRun(status!, ways!)); }
    }

    private static Dictionary<string, CardSummary> ReadBaseline(string file)
    {
        var result = new Dictionary<string, CardSummary>();
        if (!File.Exists(file)) return result;
        foreach (string line in File.ReadLines(file).Skip(1))
        {
            string[] p = line.Split('\t');
            if (p.Length < 4) continue;
            if (!result.TryGetValue(p[0], out var s)) result[p[0]] = s = new CardSummary("", new List<(string, int)>());
            if (p[1] == "status") result[p[0]] = s with { Status = p[2] };
            else s.Ways.Add((p[2], int.Parse(p[3])));
        }
        return result;
    }

    private static void WriteBaseline(string file, Dictionary<string, CardSummary> baseline)
    {
        var lines = new List<string> { "card\tway\thash\tlines" };
        foreach (var (id, s) in baseline.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            lines.Add($"{id}\tstatus\t{s.Status}\t0");
            for (int w = 0; w < s.Ways.Count; w++) lines.Add($"{id}\t{w}\t{s.Ways[w].Hash}\t{s.Ways[w].Lines}");
        }
        File.WriteAllLines(file, lines);
    }

    private static Dictionary<string, CardRun> ReadCache(string file)
    {
        if (!File.Exists(file)) return new Dictionary<string, CardRun>();
        using var gz = new GZipStream(File.OpenRead(file), CompressionMode.Decompress);
        using var reader = new StreamReader(gz, Encoding.UTF8);
        var lines = new List<string>();
        for (string? l; (l = reader.ReadLine()) != null;) lines.Add(l);
        return Parse(lines).ToDictionary(x => x.Id, x => x.Run);
    }

    private static void WriteCache(string file, Dictionary<string, CardRun> cache)
    {
        string tmp = file + ".tmp";
        using (var gz = new GZipStream(File.Create(tmp), CompressionLevel.SmallestSize))
        using (var writer = new StreamWriter(gz, new UTF8Encoding(false)))
            foreach (var (id, run) in cache.OrderBy(k => k.Key, StringComparer.Ordinal)) Write(writer, id, run);
        File.Move(tmp, file, true);
    }

    /// <summary>The first lines where the two shapes part (two before, up to eight after, each side).</summary>
    private static IEnumerable<string> FirstDifference(string oldText, string newText)
    {
        string[] a = oldText.Split('\n'), b = newText.Split('\n');
        int i = 0;
        while (i < a.Length && i < b.Length && a[i] == b[i]) i++;
        int from = Math.Max(0, i - 2);
        var result = new List<string> { $"  first difference at line {i + 1} (old {a.Length - 1} lines, new {b.Length - 1}):", "  ```" };
        for (int k = from; k < i; k++) result.Add("    " + a[k]);
        for (int k = i; k < Math.Min(a.Length, i + 8); k++) result.Add("  - " + a[k]);
        for (int k = i; k < Math.Min(b.Length, i + 8); k++) result.Add("  + " + b[k]);
        result.Add("  ```");
        return result;
    }
}

		/// <summary>Tags a minion transformed on the board keeps (live CHANGE_ENTITY): its place, owner and card history.</summary>
		private static readonly GameTag[] KeptOnTransform =
		{
			GameTag.ENTITY_ID, GameTag.CONTROLLER, GameTag.ZONE, GameTag.ZONE_POSITION, GameTag.PREMIUM,
			(GameTag)273 /* NUM_TURNS_IN_HAND */, GameTag.CREATOR, GameTag.CREATOR_DBID, (GameTag)1556 /* SPAWN_TIME_COUNT */
		};

		/// <summary>
		/// HsServer: rules E9 — a minion transformed on the board is a fresh minion of the new card. Everything the old
		/// one had is gone (keywords it gained, Divine Shield, Frozen, Silenced, Immune, damage, attacks, one-turn
		/// effects); it is newest in order of play and counts as just played (NUM_TURNS_IN_PLAY 0). Enchantments,
		/// trigger and aura are removed by the caller. Returns every tag the old one had: live's CHANGE_ENTITY lists
		/// those (with their new values) together with the new card's tags.
		/// </summary>
		internal List<GameTag> BecomeFresh(Card newCard)
		{
			var had = new List<GameTag>(_data.Keys);
			foreach (GameTag t in Card.Tags.Keys)
				if (!had.Contains(t))
					had.Add(t);

			int timesTransformed = _data.TryGetValue(TimesBeenTransformed, out int n) ? n : 0;
			var kept = new List<KeyValuePair<GameTag, int>>();
			foreach (GameTag t in KeptOnTransform)
				if (_data.TryGetValue(t, out int v))
					kept.Add(new KeyValuePair<GameTag, int>(t, v));
			_data.Clear();
			foreach (KeyValuePair<GameTag, int> kv in kept)
				_data[kv.Key] = kv.Value;
			_data[TimesBeenTransformed] = timesTransformed + 1;

			Card = newCard;
			ResetAttributes();
			_modifiedImmune = null;
			_exhausted = false;
			Game.OneTurnEffects.RemoveAll(e => e.entityId == Id);
			Game.RushMinions.Remove(Id);
			OrderOfPlay = Game.NextOop;
			return had;
		}

		private const GameTag TimesBeenTransformed = (GameTag)2321;
	}


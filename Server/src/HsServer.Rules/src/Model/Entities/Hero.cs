		public override bool HasWindfury
		{
			// HsServer: or the hero's own Windfury (Al'Akir's SWAT, INSECTS!: "your hero ... gains Windfury this turn")
			get => Weapon != null && Weapon.IsWindfury || base[GameTag.WINDFURY] > 0;
			set => Weapon.IsWindfury = value;
		}

		public override bool HasLifeSteal => Weapon?.HasLifeSteal ?? false;

